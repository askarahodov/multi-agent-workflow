"""Server-owned Git verification: real commits, forged reports and SDLC fencing."""
from __future__ import annotations

import os
import shutil
import subprocess

import pytest

from conftest import seed_workflow
from orchestration_server.engine import OrchestrationEngine
from orchestration_server.errors import ConflictError
from orchestration_server.git_commit_verifier import TrustedGitCommitVerifier


def _git(root, *args):
    return subprocess.run(
        ["git", "-C", str(root), *args],
        check=True, capture_output=True, text=True,
    ).stdout.strip()


@pytest.fixture
def trusted_repository(tmp_path):
    repo = tmp_path / "trusted-git"
    repo.mkdir()
    _git(repo, "init", "-q")
    _git(repo, "config", "user.name", "Fixture")
    _git(repo, "config", "user.email", "fixture@example.invalid")
    (repo / "README.md").write_text("baseline")
    _git(repo, "add", "README.md")
    _git(repo, "commit", "-qm", "baseline")
    return repo


def _commit(repo, task_id, attempt_id):
    out = repo / "out"
    out.mkdir(exist_ok=True)
    (out / "build.txt").write_text("native build artifact")
    _git(repo, "add", "out/build.txt")
    _git(repo, "commit", "-qm", "native artifact")
    sha = _git(repo, "rev-parse", "HEAD")
    _git(repo, "update-ref", f"refs/maw/attempts/{task_id}-{attempt_id}", sha)
    return sha


def _verifier(repo):
    return TrustedGitCommitVerifier(str(repo), os.path.realpath(shutil.which("git")))


def test_trusted_git_verifier_rejects_forged_commits_and_paths(trusted_repository):
    repo = trusted_repository
    sha = _commit(repo, "task-1", "attempt-1")
    v = _verifier(repo)
    v.verify("task-1", "attempt-1", sha, ["out/build.txt"])
    with pytest.raises(ConflictError):
        v.verify("task-2", "attempt-1", sha, ["out/build.txt"])
    with pytest.raises(ConflictError):
        v.verify("task-1", "attempt-1", "a" * 40, ["out/build.txt"])
    with pytest.raises(ConflictError):
        v.verify("task-1", "attempt-1", sha, ["out/missing.txt"])
    with pytest.raises(ConflictError):
        v.verify("../task", "attempt-1", sha, ["out/build.txt"])


@pytest.mark.asyncio
async def test_server_rejects_unattested_commit_before_contract_transition(
    harness, trusted_repository,
):
    _, _, agent, run, tasks = await seed_workflow(harness.orch, harness.queries)
    orch = OrchestrationEngine(
        harness.sf, require_lease=True, require_git_artifact=True,
        git_commit_verifier=_verifier(trusted_repository),
    )
    # Leases are generated by the API, not this minimal engine; claim a leased
    # attempt directly using the server-owned API with the same SQLite state.
    from orchestration_server.api import build_app
    from orchestration_server.config import Settings
    import httpx

    app = build_app(Settings(
        database_url=harness.url, recover_on_startup=False,
        attempt_lease_enabled=True, require_git_artifact=True,
        git_verification_repository=str(trusted_repository),
        git_verification_executable=os.path.realpath(shutil.which("git")),
    ))
    async with app.router.lifespan_context(app):
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app),
            base_url="https://control.example",
        ) as client:
            claimed = await client.post(
                f"/api/v1/tasks/{tasks[0].id}/claim",
                json={"agent_id": agent.id},
            )
            assert claimed.status_code == 201, claimed.text
            attempt = claimed.json()
            target = f"/api/v1/tasks/{tasks[0].id}/attempts/{attempt['id']}/submit"
            params = {"agent_id": agent.id}
            headers = {"X-Attempt-Lease": attempt["lease_token"]}
            forged = await client.post(
                target, params=params, headers=headers,
                json={"output": {"summary": "valid JSON but fake Git"},
                      "git_artifact": {"commit_sha": "a" * 40, "changed_paths": ["out/build.txt"]}},
            )
            assert forged.status_code == 409
            assert (await harness.queries.get_task(tasks[0].id)).status == "in_progress"
            assert (await harness.queries.get_run(run.id)).status == "running"
            sha = _commit(trusted_repository, tasks[0].id, attempt["id"])
            good = await client.post(
                target, params=params, headers=headers,
                json={"output": {"summary": "valid Git and contract"},
                      "git_artifact": {"commit_sha": sha, "changed_paths": ["out/build.txt"]}},
            )
            assert good.status_code == 200, good.text
            assert good.json()["status"] == "completed"
    assert (await harness.queries.get_run(run.id)).status == "completed"
